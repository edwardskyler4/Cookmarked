-- Minimal Supabase contracts for an isolated PostgreSQL test database.
create role anon nologin;
create role authenticated nologin;
create role supabase_auth_admin nologin;
create schema auth;
create table auth.users (id uuid primary key, email text unique, raw_user_meta_data jsonb default '{}');
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
grant usage on schema auth to authenticated;
grant execute on function auth.uid() to authenticated;
create table public.profile (user_id bigint generated by default as identity primary key, username text not null);
-- Simulate an old overly broad policy: the migration must still isolate users.
alter table public.profile enable row level security;
create policy legacy_read_all on public.profile for select to authenticated using (true);
grant all on public.profile to anon, authenticated;
-- Simulate the previously deployed table that the follow-up migration must isolate.
create table public."Users" (user_id bigint generated by default as identity primary key, username text not null);
alter table public."Users" enable row level security;
create policy legacy_users_read_all on public."Users" for select to authenticated using (true);
grant all on public."Users" to anon, authenticated;

-- Existing recipe schema supplied by the student; no access policies yet.
create table public.recipe (
  recipe_id integer generated by default as identity primary key,
  user_id integer not null references public.profile(user_id),
  title varchar(45) not null, note text, ingredients text, instructions text,
  prep_time varchar(45), cook_time varchar(45), servings integer,
  meal_type text not null check (meal_type in ('Breakfast','Lunch','Dinner','Supper','Snack','N/A')),
  course text not null check (course in ('Dessert','Entree','Side','Beverage','Appetizer','N/A')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  shared_from_platform text, url text, media_type varchar(45), thumbnail_url text, nutrition_info text
);
alter table public.recipe enable row level security;
