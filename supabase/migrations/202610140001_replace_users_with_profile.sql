begin;

-- Dev may already have the original Users table because the first migration was
-- recorded as applied before the table was renamed in source control.
do $$
begin
  if to_regclass('public.profile') is null
     and to_regclass('public."Users"') is not null then
    alter table public."Users" rename to profile;
  end if;
end;
$$;

create table if not exists public.profile (
  user_id bigint generated by default as identity primary key,
  username text not null
);

alter table public.profile
  add column if not exists auth_user_id uuid unique references auth.users(id) on delete cascade;

create unique index if not exists profile_auth_username_unique
  on public.profile (lower(username)) where auth_user_id is not null;

create or replace function public.create_auth_profile() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  canonical_username text;
begin
  canonical_username := substring(new.email from '^([a-z0-9_]{3,32})@accounts[.]cookmarked[.]edw20009[.]workers[.]dev$');
  if canonical_username is null then
    raise exception 'Invalid Cookmarked account identifier' using errcode = '23514';
  end if;
  insert into public.profile (username, auth_user_id) values (canonical_username, new.id);
  return new;
end;
$$;

drop trigger if exists cookmarked_create_auth_profile on auth.users;
create trigger cookmarked_create_auth_profile
  after insert on auth.users for each row execute function public.create_auth_profile();

create or replace function public.keep_auth_identifier() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.email is distinct from old.email then
    raise exception 'Cookmarked account identifiers cannot be changed' using errcode = '23514';
  end if;
  return new;
end;
$$;

drop trigger if exists cookmarked_keep_auth_identifier on auth.users;
create trigger cookmarked_keep_auth_identifier
  before update of email on auth.users for each row execute function public.keep_auth_identifier();

alter table public.profile enable row level security;
revoke all on public.profile from public, anon, authenticated;
grant select on public.profile to authenticated;

drop policy if exists users_read_own on public.profile;
drop policy if exists users_owner_boundary on public.profile;
drop policy if exists profile_read_own on public.profile;
drop policy if exists profile_owner_boundary on public.profile;

create policy profile_read_own on public.profile
  for select to authenticated using ((select auth.uid()) = auth_user_id);
create policy profile_owner_boundary on public.profile as restrictive
  for all to authenticated
  using ((select auth.uid()) = auth_user_id)
  with check ((select auth.uid()) = auth_user_id);

-- Keep the old table out of the browser-facing data path without deleting data.
do $$
begin
  if to_regclass('public."Users"') is not null then
    revoke all on public."Users" from public, anon, authenticated;
  end if;
end;
$$;

commit;
